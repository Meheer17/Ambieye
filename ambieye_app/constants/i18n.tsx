const LANGUAGE_STORAGE_KEY = "ambieye_selected_language";

interface LanguageContextType {
  currentLang: SupportedLanguage;
  changeLanguage: (lang: SupportedLanguage) => Promise<void>;
  t: (key: string) => string;
  supportedLanguages: LanguageOption[];
}

export const LanguageContext = createContext<LanguageContextType>({
  currentLang: "as",
  changeLanguage: async () => {},
  t: (k) => k,
  supportedLanguages: SUPPORTED_LANGUAGES,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLang, setCurrentLang] = useState<SupportedLanguage>("as");

  useEffect(() => {
    AsyncStorage.getItem(LANGUAGE_STORAGE_KEY)
      .then((saved) => {
        if (saved && saved in TRANSLATIONS) {
          setCurrentLang(saved as SupportedLanguage);
        }
      })
      .catch((err) => console.error("Failed loading language", err));
  }, []);

  const changeLanguage = useCallback(async (lang: SupportedLanguage) => {
    setCurrentLang(lang);
    try {
      await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch (e) {
      console.error("Failed saving language", e);
    }
  }, []);

  const t = useCallback(
    (key: string): string => {
      const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
      if (dict && key in dict) {
        return dict[key];
      }
      return TRANSLATIONS.en[key] || key;
    },
    [currentLang]
  );

  return (
    <LanguageContext.Provider value={{ currentLang, changeLanguage, t, supportedLanguages: SUPPORTED_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useTranslation = () => useContext(LanguageContext);
